#!/usr/bin/env python3
"""Generate pinyin TSV and syllable components from Rime Ice character dictionaries.

Python is a maintainer dependency only. Source dictionaries are supplied locally;
this script performs no downloads and preserves their enabled text/code pairs.
"""
import argparse
from pathlib import Path
import re

PUNCTUATION = {
    '￥': ['$'],
    '·': ['`'],
    '—': ['_'],
    '…': ['^'],
    '〕': [']'],
    '〔': ['['],
    '』': ['}'],
    '『': ['{'],
    '」': [']'],
    '「': ['['],
    '〉': ['>'],
    '〈': ['<'],
    '》': ['>'],
    '《': ['<'],
    '】': [']'],
    '【': ['['],
    '）': [')'],
    '（': ['('],
    '’': ["'"],
    '‘': ["'"],
    '”': ['"'],
    '“': ['"'],
    '！': ['!'],
    '？': ['?'],
    '：': [':'],
    '；': [';'],
    '、': ['/', '\\'],
    '。': ['.'],
    '，': [','],
}


INITIAL = re.compile(r"^(zh|ch|sh|[bpmfdtnlgkhjqxrzcsyw])")


def read_dictionary(path):
    rows = {}
    in_data = False
    for number, line in enumerate(path.read_text(encoding="utf-8-sig").splitlines(), 1):
        if not in_data:
            in_data = line.strip() == "..."
            continue
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        fields = line.split("\t")
        if len(fields) < 2:
            raise ValueError(f"{path}:{number}: missing text/code")
        text, code = fields[0].strip(), fields[1].strip()
        if len(text) != 1 or not re.fullmatch("[a-z]+", code):
            raise ValueError(f"{path}:{number}: expected one character and lowercase pinyin")
        rows.setdefault(text, set()).add(code)
    if not in_data:
        raise ValueError(f"{path}: missing Rime header terminator")
    return rows


def main():
    root = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("sources", type=Path, nargs="+")
    parser.add_argument("--output", type=Path, default=root / "lua/flash-any/tables/pinyin.tsv")
    parser.add_argument("--parts", type=Path, default=root / "lua/flash-any/pinyin/parts.lua")
    args = parser.parse_args()
    rows = {}
    for source in args.sources:
        for text, codes in read_dictionary(source).items():
            rows.setdefault(text, set()).update(codes)
    syllables = sorted({code for codes in rows.values() for code in codes})
    components = {}
    for syllable in syllables:
        match = INITIAL.match(syllable)
        initial = match[0] if match else ""
        components[syllable] = (initial, syllable[len(initial):])
    for text, codes in PUNCTUATION.items():
        rows.setdefault(text, set()).update(codes)
    with args.output.open("w", encoding="utf-8") as output:
        for text in sorted(rows):
            for code in sorted(rows[text]):
                output.write(f"{text}\t{code}\n")
    with args.parts.open("w", encoding="utf-8") as output:
        output.write("-- Generated by scripts/build.py from the same Rime Ice syllables as pinyin.tsv.\nreturn {\n")
        for index, name in enumerate(("initial", "final")):
            output.write(f"\t{name} = {{\n")
            for syllable, parts in components.items():
                output.write(f'\t\t["{syllable}"] = "{parts[index]}",\n')
            output.write("\t},\n")
        output.write("}\n")
    print(f"wrote {len(rows)} characters, {sum(map(len, rows.values()))} codes, {len(syllables)} syllables")


if __name__ == "__main__":
    main()
